#!/usr/bin/env bash
# Redraw the keymap picture shown in README.md:
#   config/corne.keymap -> keymap-drawer/corne.yaml -> keymap-drawer/corne.svg
# Needs uv (https://docs.astral.sh/uv/); uvx fetches keymap-drawer at the pinned version.
#
#   scripts/draw-keymap.sh          regenerate (files are replaced only if both steps succeed)
#   scripts/draw-keymap.sh --check  exit 0 if the outputs match the current inputs, 1 otherwise
#   scripts/draw-keymap.sh --hash   print the hash of the current inputs
set -euo pipefail

cd "$(dirname "$0")/.."

KEYMAP_DRAWER_VERSION=0.23.0
KEYMAP=config/corne.keymap
CONFIG=keymap_drawer.config.yaml
OUT_DIR=keymap-drawer
STAMP="$OUT_DIR/.inputs.sha256"

inputs_hash() {
  cat "$KEYMAP" "$CONFIG" scripts/draw-keymap.sh | shasum -a 256 | cut -d' ' -f1
}

case "${1:-}" in
  --hash)
    inputs_hash
    exit 0
    ;;
  --check)
    if [[ -f "$STAMP" && "$(cat "$STAMP")" == "$(inputs_hash)" ]]; then exit 0; else exit 1; fi
    ;;
  "") ;;
  *)
    echo "usage: $0 [--check|--hash]" >&2
    exit 2
    ;;
esac

if ! command -v uvx >/dev/null 2>&1; then
  echo "draw-keymap: uvx not found; install uv (https://docs.astral.sh/uv/)" >&2
  exit 127
fi

kd() { uvx --quiet --from "keymap-drawer==$KEYMAP_DRAWER_VERSION" keymap -c "$CONFIG" "$@"; }

hash=$(inputs_hash)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

{
  echo "# Generated by scripts/draw-keymap.sh from $KEYMAP. Do not edit."
  kd parse -z "$KEYMAP"
} > "$tmp/corne.yaml"
kd draw "$tmp/corne.yaml" > "$tmp/corne.svg"

mkdir -p "$OUT_DIR"
mv "$tmp/corne.yaml" "$tmp/corne.svg" "$OUT_DIR/"
echo "$hash" > "$STAMP"
echo "draw-keymap: updated $OUT_DIR/corne.yaml and $OUT_DIR/corne.svg"
